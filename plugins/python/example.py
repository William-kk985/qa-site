# 示例插件（Python 写的）—— 和 C / C++ / Rust / MoonBit / TS / ReScript / JS 那几版
# **语义完全一样**。
#
# ============================================================================
# ⚠️ Python 和前面几门语言有个本质区别，先看这里
# ============================================================================
#
# 其它语言都是「编译成 .wasm / .js，把产物传上去」。
# Python 不行 —— Python 的**运行时本身**就是一大坨 wasm（CPython 编成 wasm
# 的那个项目叫 Pyodide），光核心就 ~9.6MB，加标准库 ~12MB。
#
#   12MB 是不可能塞进浏览器 localStorage 的（上限 5MB 左右），
#   也不该提交进仓库（谁 clone 都得拖下来）。
#
# 所以 Python 这条路是这么走的：
#
#   · 你上传的：**就是这个 .py 源码文件**，几百字节
#   · 存在哪：  照旧只存在你自己浏览器的 localStorage 里
#   · 运行时：  只有当你真的用了 Python 插件，页面才会去 CDN 拉一次 Pyodide
#               （拉完浏览器会缓存，同一台机器下次就快了）
#   · 没装 Python 插件的人：**一个字节都不会下载**，完全不受影响
#
# 代价说清楚：第一次用会等十几秒 + 十几 MB 流量，而且依赖 CDN 能不能连上。
# 如果你只是想改个颜色，用别的语言（或者直接写自定义 CSS）要划算得多。
# Python 适合的场景是"我就想用 Python 写这段逻辑"。
#
# ============================================================================
# 约定（和别的语言一模一样，没有 Python 特殊的地方）
# ============================================================================
#
#   ① theme(i) -> 数字
#      i 是槽位号；返回**负数 = 这个槽位用站点默认值**，所以可以只改想改的。
#      槽位表和范围见 plugins/README.md（网页上的「插件」页签里也有一份）。
#
#   ② hot_score(点赞, 回答, 浏览, 距今天数) -> 数字
#      替换「热门」标签的排序算法，越大越靠前。
#
# 两个都定义可以，只定义一个也行。两个都没有，上传时会被拒。
#
# 不用 import 任何东西 —— 这个 ABI 是纯数字进出的，用不上标准库。
# （真要用 math 也行，但那会让 Pyodide 多加载一点东西。）


def theme(i):
    """外观槽位。返回负数表示"这个槽位用站点默认"。"""
    if i == 0:
        return 152.0   # 主题色 色相 0–360（152 ≈ 森林绿）
    if i == 1:
        return 0.62    # 主题色 饱和度 0–1
    if i == 2:
        return 0.42    # 主题色 亮度 0–1
    if i == 3:
        return 2.0     # 圆角 px 0–24（2 ≈ 接近直角）
    if i == 4:
        return 1240.0  # 页面最大宽度 px 700–1600
    if i == 5:
        return 17.0    # 正文字号 px 12–20
    if i == 6:
        return 22.0    # 卡片内边距 px 0–40
    if i == 7:
        return 16.0    # 列表间距 px 0–30
    return -1.0        # 没定义的槽位 → 用默认


def hot_score(votes, answers, views, age_days):
    """热门排序打分：越大越靠前。"""
    base = votes * 3 + answers * 5 + views / 100
    # 时间衰减：30 天前发的，热度打对折，防止老帖永远霸榜
    return base / (1 + age_days / 30)


# ===========================================================================
# ③ 搜索相关度打分：search_score(query, text) -> float
# ---------------------------------------------------------------------------
# Python 和 JS 一样，**不需要任何协议** —— 字符串是原生的。
# （wasm 那边要 qa_buffer + 线性内存，见 c/example.c 的长注释。）
#
# ⚠️ 打分算法必须和别的语言**逐位一致**，所以这里先 encode 成 UTF-8 字节
#    再逐字节比。直接按 Python 的字符遍历的话，中文会和 wasm 侧对不上。
# ===========================================================================
def search_score(query, text):
    """query 越相关分越高。纯 ASCII 大小写不敏感，中文按 UTF-8 字节比。"""
    q = query.encode("utf-8")
    t = text.encode("utf-8")
    if not q:
        return 0.0
    score = 0.0
    for qc in q:
        c = qc + 32 if 65 <= qc <= 90 else qc
        if c == 32:
            continue
        n = 0
        for tc in t:
            if (tc + 32 if 65 <= tc <= 90 else tc) == c:
                n += 1
        score += n
    return score / len(q)
